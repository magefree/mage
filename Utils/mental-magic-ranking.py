"""
Builds the card ranking used to sort the card choices of Mental Magic games:
Mage/src/main/resources/mentalmagic/card-ranking.txt

Data comes from Scryfall:
  - MTGO Vintage Cube cards (search "cube:vintage"), listed first. Cube cards banned in Commander
    (Power 9 etc.) go to the top, because their EDHREC rank doesn't show their power;
  - EDHREC popularity rank (oracle cards bulk data) for everything else.

Usage: python mental-magic-ranking.py [output file] [max names]
"""
import gzip
import json
import os
import sys
import tempfile
import time
import urllib.request

DEFAULT_OUTPUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Mage", "src", "main", "resources",
                              "mentalmagic", "card-ranking.txt")
DEFAULT_MAX_NAMES = 10000
HEADERS = {"User-Agent": "XMageMentalMagicRanking/1.0", "Accept": "application/json"}
SKIP_LAYOUTS = {"token", "double_faced_token", "emblem", "art_series", "vanguard", "scheme", "planar", "reversible_card"}


def get_json(url):
    req = urllib.request.Request(url, headers=HEADERS)
    with urllib.request.urlopen(req) as resp:
        return json.load(resp)


def download(url, path):
    req = urllib.request.Request(url, headers=HEADERS)
    with urllib.request.urlopen(req) as resp, open(path, "wb") as out:
        while True:
            chunk = resp.read(1 << 20)
            if not chunk:
                break
            out.write(chunk)


def card_names(card):
    names = {card["name"]}
    for face in card.get("card_faces", []):
        names.add(face["name"])
    return names


def vintage_cube_names():
    names = set()
    url = "https://api.scryfall.com/cards/search?q=cube%3Avintage&unique=cards"
    while url:
        page = get_json(url)
        for card in page["data"]:
            names.update(card_names(card))
        url = page.get("next_page")
        time.sleep(0.1)  # Scryfall asks for 50-100 ms between requests
    return names


def edhrec_ranks():
    """name -> (best edhrec rank or None, banned in commander)"""
    bulk = next(b for b in get_json("https://api.scryfall.com/bulk-data")["data"] if b["type"] == "oracle_cards")
    res = {}
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "oracle-cards.jsonl.gz")
        print("downloading", bulk["jsonl_download_uri"])
        download(bulk["jsonl_download_uri"], path)
        with gzip.open(path, "rt", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                card = json.loads(line)
                if card.get("layout") in SKIP_LAYOUTS:
                    continue
                rank = card.get("edhrec_rank")
                banned = card.get("legalities", {}).get("commander") == "banned"
                for name in card_names(card):
                    old_rank, old_banned = res.get(name, (None, False))
                    if old_rank is not None and (rank is None or old_rank < rank):
                        rank = old_rank
                    res[name] = (rank, banned or old_banned)
    return res


def build_ranking(ranks, cube, max_names):
    def cube_key(name):
        rank, banned = ranks.get(name, (None, False))
        return (0 if banned or rank is None else rank, name)

    cube_list = sorted(cube, key=cube_key)
    popular = sorted((rank, name) for name, (rank, _) in ranks.items() if rank is not None and name not in cube)
    popular_list = [name for _, name in popular][:max(0, max_names - len(cube_list))]
    return cube_list, popular_list


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUTPUT
    max_names = int(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_MAX_NAMES

    cube = vintage_cube_names()
    print("vintage cube names:", len(cube))
    ranks = edhrec_ranks()
    cube_list, popular_list = build_ranking(ranks, cube, max_names)

    with open(out_path, "w", encoding="utf-8", newline="\n") as out:
        out.write("# Mental Magic card ranking, best cards first. Generated by Utils/mental-magic-ranking.py\n")
        out.write("# Data: Scryfall (MTGO Vintage Cube list and EDHREC popularity rank)\n")
        out.write("#cube\n")
        out.writelines(name + "\n" for name in cube_list)
        out.write("#popular\n")
        out.writelines(name + "\n" for name in popular_list)
    print("wrote", len(cube_list) + len(popular_list), "names to", out_path)


if __name__ == "__main__":
    main()
