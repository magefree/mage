from urllib.request import Request, urlopen

UTILS_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(UTILS_DIR, "data", "17lands")
SETS_JAVA_DIR = os.path.join(UTILS_DIR, "..", "Mage.Sets", "src", "mage", "sets")
RATINGS_DIR = os.path.join(UTILS_DIR, "..", "Mage", "src", "main", "resources", "ratings")
RATINGS_SET_LIST = os.path.join(RATINGS_DIR, "setsWithRatings.csv")

USER_AGENT = "XMage Dev Utils"
FILTERS_URL = "https://www.17lands.com/data/filters"
DATA_URL = "https://17lands-public.s3.amazonaws.com/analysis_data/{kind}_data/{kind}_data_public.{code}.PremierDraft.csv.gz"
DATA_KINDS = ("draft", "game")
SETS_CACHE_FILE = os.path.join(DATA_DIR, "sets.json")
SETS_CACHE_HOURS = 24

DEFAULT_SETS_LIST_HEADER = [
    "# auto-generated file, sets with precalculated and normalized ratings [1..100]",
    "# data source:",
    "# - draftaholicsanonymous - outdated and manually created, only old sets use it",
    "# - 17Lands - actual data, auto-generated by python Utils/gen-draft-rates-17Lands.py",
]
GENERATED_MARK = "# generated by Utils/gen-draft-rates-17Lands.py from 17Lands.com public datasets (CC BY 4.0)"
DATA_DATE_LINE = "# 17Lands data from {date} (timestamp {timestamp})"  # warning, no ":" here, RateCard parses lines by it
DATA_DATE_RE = re.compile(r"^# 17Lands data from .* \(timestamp (\d+)\)$")
OWN_FILE_RE = re.compile(r"^((draft|game)_data_public\.\w+\.PremierDraft\.csv\.gz(\.part)?|sets\.json)$")
MIN_GAMES_IN_HAND = 500
EARLY_PICKS = 4  # pick numbers 0..3 of every pack
BASIC_LANDS = {"Plains", "Island", "Swamp", "Mountain", "Forest", "Wastes"}

SET_CLASS_RE = re.compile(r'super\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*"([A-Za-z0-9]+)"')
SET_CARD_INFO_RE = re.compile(r'new SetCardInfo\(\s*"((?:[^"\\]|\\.)*)"\s*,')


# ---------- network ----------

def http_request(url, method="GET"):
    return urlopen(Request(url, method=method, headers={"User-Agent": USER_AGENT}), timeout=60)


def remote_file_info(url):
    """Returns (size, last modified) of a remote file or None if it's not available."""
    try:
        with http_request(url, method="HEAD") as response:
            return int(response.headers.get("Content-Length", 0)), response.headers.get("Last-Modified", "")
    except HTTPError as e:
        if e.code in (403, 404):
            return None
        raise SystemExit(f"HTTP error {e.code} for {url}")
    except URLError as e:
        raise SystemExit(f"Network error for {url}: {e.reason}")


def download_file(url, path, progress_prefix):
    tmp_path = path + ".part"
    try:
        with http_request(url) as response, open(tmp_path, "wb") as f:
            last_modified = response.headers.get("Last-Modified", "")
            total = int(response.headers.get("Content-Length", 0))
            done = 0
            while True:
                chunk = response.read(1024 * 1024)
                if not chunk:
                    break
                f.write(chunk)
                done += len(chunk)
                percent = f" ({100 * done // total}%)" if total else ""
                print(f"\r{progress_prefix}: {mb(done)} / {mb(total)}{percent}   ", end="", flush=True)
        os.replace(tmp_path, path)  # no broken files after an interrupted download
        timestamp = to_timestamp(last_modified)
        if timestamp:
            os.utime(path, (timestamp, timestamp))  # keep 17Lands date to find outdated files later
        print()
    except (HTTPError, URLError) as e:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)
        raise SystemExit(f"\nDownload failed for {url}: {e}")


def sets_count(amount):
    return f"{amount} set" + ("" if amount == 1 else "s")


def mb(size):
    return f"{size / 1024 / 1024:.1f} MB"


def to_timestamp(http_date):
    """HTTP date like "Fri, 17 Oct 2026 12:00:00 GMT" to unix time, 0 if unknown"""
    try:
        return int(parsedate_to_datetime(http_date).timestamp()) if http_date else 0
    except (TypeError, ValueError):
        return 0


def to_date(timestamp):
    return time.strftime("%Y-%m-%d", time.gmtime(timestamp)) if timestamp else "?"


# ---------- local data ----------

def load_xmage_sets():
    """Returns {code: (set name, java file)} of all XMage sets."""
    res = {}
    for file in sorted(os.listdir(SETS_JAVA_DIR)):
        if not file.endswith(".java"):
            continue
        path = os.path.join(SETS_JAVA_DIR, file)
        with open(path, encoding="utf-8") as f:
            found = SET_CLASS_RE.search(f.read())
        if found:
            res[found.group(2).upper()] = (found.group(1), path)
    return res


def load_xmage_set_cards(java_file):
    with open(java_file, encoding="utf-8") as f:
        return {name.replace('\\"', '"') for name in SET_CARD_INFO_RE.findall(f.read())}


def load_own_ratings():
    """Returns {CODE: (cards amount, is generated by this script, timestamp of its 17Lands data)} of all rating files."""
    res = {}
    for file in os.listdir(RATINGS_DIR):
        code, ext = os.path.splitext(file)
        if ext != ".csv" or file == os.path.basename(RATINGS_SET_LIST):
            continue
        with open(os.path.join(RATINGS_DIR, file), encoding="utf-8") as f:
            lines = f.read().splitlines()
        cards = sum(1 for line in lines if ":" in line and not line.startswith("#"))
        data_timestamps = [int(m.group(1)) for m in map(DATA_DATE_RE.match, lines) if m]
        res[code.upper()] = (cards, GENERATED_MARK in lines, data_timestamps[0] if data_timestamps else 0)
    return res


def data_file_path(code, kind):
    return os.path.join(DATA_DIR, f"{kind}_data_public.{code}.PremierDraft.csv.gz")


def is_downloaded(code):
    return all(os.path.exists(data_file_path(code, kind)) for kind in DATA_KINDS)


def remote_timestamp(info):
    """Date of the newest 17Lands file of the set"""
    return max(to_timestamp(info[kind][1]) for kind in DATA_KINDS)


def file_status(code, kind, info):
    path = data_file_path(code, kind)
    if not os.path.exists(path):
        return "missing"
    remote = to_timestamp(info[kind][1])
    if remote and os.path.getmtime(path) < remote - 1:
        return "outdated"
    return "ok"


def data_status(code, info):
    """Downloaded data of the set: yes / outdated / part / -"""
    statuses = [file_status(code, kind, info) for kind in DATA_KINDS]
    if all(status == "missing" for status in statuses):
        return "-"
    if "outdated" in statuses:
        return "outdated"
    if "missing" in statuses:
        return "part"
    return "yes"


def is_ratings_outdated(code, own_ratings, info):
    if code not in own_ratings or not own_ratings[code][1]:
        return False
    return own_ratings[code][2] < remote_timestamp(info)


def own_data_files():
    """Own files in the data folder (it can contain files of other scripts)"""
    if not os.path.isdir(DATA_DIR):
        return []
    return [os.path.join(DATA_DIR, file) for file in sorted(os.listdir(DATA_DIR)) if OWN_FILE_RE.match(file)]


def files_size(files):
    return sum(os.path.getsize(file) for file in files)


def load_17lands_sets(xmage_sets):
    """Returns [{code, draft: [size, date], game: [size, date]}] of 17Lands sets with PremierDraft data, newest first."""
    if os.path.exists(SETS_CACHE_FILE) and time.time() - os.path.getmtime(SETS_CACHE_FILE) < SETS_CACHE_HOURS * 3600:
        print("Using cached 17Lands sets list")
        with open(SETS_CACHE_FILE, encoding="utf-8") as f:
            return json.load(f)

    print("Fetching 17Lands sets list ...")
    try:
        with http_request(FILTERS_URL) as response:
            filters = json.loads(response.read().decode("utf-8"))
    except (HTTPError, URLError) as e:
        raise SystemExit(f"Can't load 17Lands sets list from {FILTERS_URL}: {e}")
    formats = filters.get("formats_by_expansion", {})
    codes = [code for code in filters.get("expansions", [])
             if code.upper() in xmage_sets and "PremierDraft" in formats.get(code, [])]

    res = []
    for num, code in enumerate(codes, 1):
        print(f"\rChecking 17Lands public datasets: {num} / {sets_count(len(codes))}   ", end="", flush=True)
        info = {"code": code.upper()}
        for kind in DATA_KINDS:
            info[kind] = remote_file_info(DATA_URL.format(kind=kind, code=code))
        if all(info[kind] for kind in DATA_KINDS):
            res.append(info)
    print()
    os.makedirs(DATA_DIR, exist_ok=True)
    with open(SETS_CACHE_FILE, "w", encoding="utf-8") as f:
        json.dump(res, f, indent=1)
    return res


