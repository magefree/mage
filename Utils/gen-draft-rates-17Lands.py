def parse_codes(args):
    if not args:
        return None
    return [code.strip().upper() for code in ",".join(args).split(",") if code.strip()]


def downloaded_codes():
    if not os.path.isdir(DATA_DIR):
        return []
    found = re.compile(r"draft_data_public\.(\w+)\.PremierDraft\.csv\.gz$")
    codes = [m.group(1) for m in map(found.match, sorted(os.listdir(DATA_DIR))) if m]
    return [code for code in codes if is_downloaded(code)]


def is_ratings_older_than_data(code, own_ratings):
    """Generated ratings made from older data than the downloaded files (works without network)"""
    if code not in own_ratings or not own_ratings[code][1] or not is_downloaded(code):
        return False
    local = int(max(os.path.getmtime(data_file_path(code, kind)) for kind in DATA_KINDS))
    return own_ratings[code][2] < local


def codes_to_collect(own_ratings):
    return [code for code in downloaded_codes()
            if code not in own_ratings or is_ratings_older_than_data(code, own_ratings)]


def files_to_clean(own_ratings):
    """Data of the sets with generated ratings from the same data + broken downloads"""
    res = []
    for path in own_data_files():
        file = os.path.basename(path)
        if file.endswith(".part"):
            res.append(path)
            continue
        found = re.match(r"(draft|game)_data_public\.(\w+)\.PremierDraft\.csv\.gz$", file)
        if not found:
            continue  # sets list cache
        code = found.group(2)
        if code in own_ratings and own_ratings[code][1] and not is_ratings_older_than_data(code, own_ratings):
            res.append(path)
    return res


def clean_data(own_ratings):
    files = files_to_clean(own_ratings)
    if not files:
        print("Nothing to clean")
        return
    size = files_size(files)
    for num, path in enumerate(files, 1):
        print(f"[{num}/{len(files)}] delete {os.path.basename(path)}")
        os.remove(path)
    print(f"Deleted {len(files)} files, {mb(size)} freed")


def print_data_size():
    files = own_data_files()
    print(f"17Lands data in Utils/{os.path.relpath(DATA_DIR, UTILS_DIR)}: {len(files)} files, {mb(files_size(files))}")


def main():
    mode = sys.argv[1].lower() if len(sys.argv) > 1 else ""
    if mode not in ("", "-download", "-collect", "-clean"):
        raise SystemExit(__doc__)
    codes = parse_codes(sys.argv[2:])
    print_data_size()
    xmage_sets = load_xmage_sets()
    own_ratings = load_own_ratings()
    listed = update_sets_list()

    # modes without network
    if mode == "-collect":
        collect_sets(codes or codes_to_collect(own_ratings), xmage_sets, own_ratings, listed)
        return
    if mode == "-clean":
        clean_data(own_ratings)
        return

    sets_17lands = load_17lands_sets(xmage_sets)
    available = [info["code"] for info in sets_17lands]
    without_ratings = [code for code in available if code not in own_ratings]
    # data to update: outdated downloads + sets with outdated ratings without fresh data (example: cleaned after collect)
    outdated = [info["code"] for info in sets_17lands
                if data_status(info["code"], info) == "outdated"
                or (is_ratings_outdated(info["code"], own_ratings, info) and data_status(info["code"], info) != "yes")]
    if mode == "-download":
        download_sets(codes or without_ratings + [code for code in outdated if code not in without_ratings],
                      sets_17lands)
        return

    # interactive mode
    rows = build_rows(xmage_sets, sets_17lands, own_ratings, listed)
    print_table(rows)
    not_downloaded = [code for code in without_ratings if not is_downloaded(code)]
    to_collect = codes_to_collect(own_ratings)
    to_clean = files_to_clean(own_ratings)
    outdated_ratings = [code for code in available if is_ratings_outdated(code, own_ratings,
                                                                          sets_17lands[available.index(code)])]
    print(f"XMage sets with 17Lands PremierDraft data: {len(available)}, without our ratings: {len(without_ratings)}, "
          f"not downloaded: {len(not_downloaded)}, outdated data: {len(outdated)}, outdated ratings: {len(outdated_ratings)}")
    print()
    recommended = print_status(check_environment(), not_downloaded, outdated, to_collect, to_clean)

    def set_size(set_codes):
        return mb(sum(info["draft"][0] + info["game"][0] for info in sets_17lands if info["code"] in set_codes))

    # all menu items are visible, an item without work is disabled with a reason
    first = without_ratings[0] if without_ratings else None
    actions = [
        ("1", f"download and collect {first} (first set without ratings)" if first
              else "download and collect the first set without ratings",
         "disabled, all sets have ratings" if not first else None,
         lambda: (download_sets([first], sets_17lands), collect_sets([first], xmage_sets, own_ratings, listed))),
        ("2", "download all missing data" + (f" ({sets_count(len(not_downloaded))}, {set_size(not_downloaded)})" if not_downloaded else ""),
         "disabled, all sets without ratings are downloaded" if not not_downloaded else None,
         lambda: download_sets(not_downloaded, sets_17lands)),
        ("3", "collect all downloaded sets without ratings or with older ratings" + (f" ({sets_count(len(to_collect))})" if to_collect else ""),
         "disabled, nothing to collect" if not to_collect else None,
         lambda: collect_sets(to_collect, xmage_sets, own_ratings, listed)),
        ("4", "update outdated data" + (f" ({sets_count(len(outdated))}, {set_size(outdated)})" if outdated else ""),
         "disabled, all data and ratings are up to date" if not outdated else None,
         lambda: download_sets(outdated, sets_17lands)),
        ("5", "clean data of the sets with ratings" + (f" ({len(to_clean)} files, {mb(files_size(to_clean))})" if to_clean else ""),
         "disabled, nothing to clean" if not to_clean else None,
         lambda: clean_data(own_ratings)),
    ]
    print()
    for key, text, disabled, _ in actions:
        mark = " <- next step" if key == recommended and not disabled else ""
        print(f"  {key} - {text}" + (f" - {disabled}" if disabled else "") + mark)
    print("  or type set codes to download and collect it (example: fra or fra,hob), empty to exit")
    answer = input("> ").strip()
    if not answer:
        return
    for key, text, disabled, action in actions:
        if answer == key:
            if disabled:
                print(f"Item {key} is {disabled}")
            else:
                action()
            return
    codes = parse_codes([answer])
    download_sets(codes, sets_17lands)
    collect_sets(codes, xmage_sets, own_ratings, listed)


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\nStopped")