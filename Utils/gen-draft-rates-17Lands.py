def print_table(rows):
    print()
    print(f"{'code':<6} {'XMage set':<32} {'our ratings':<42} {'17Lands data (draft + game)':<30} {'downloaded'}")
    for row in rows:
        print(f"{row['code']:<6} {row['name'][:32]:<32} {row['ratings']:<42} {row['data']:<30} {row['downloaded']}")
    print()


def build_rows(xmage_sets, sets_17lands, own_ratings, listed):
    rows = []
    known = set()
    for info in sets_17lands:
        code = info["code"]
        known.add(code)
        size = info["draft"][0] + info["game"][0]
        date = info["draft"][1][5:16] if info["draft"][1] else ""  # "Thu, 17 Oct 2026 ..." -> "17 Oct 2026"
        status = ratings_status(code, own_ratings, listed)
        if is_ratings_outdated(code, own_ratings, info):
            status += ", OUTDATED"
        rows.append({"code": code, "name": xmage_sets.get(code, ("?",))[0], "ratings": status,
                     "data": f"{mb(size)}, {date}", "downloaded": data_status(code, info), "available": True})
    for code in sorted(own_ratings):
        if code not in known:
            rows.append({"code": code, "name": xmage_sets.get(code, ("?",))[0],
                         "ratings": ratings_status(code, own_ratings, listed),
                         "data": "-", "downloaded": "-", "available": False})
    return rows


def ratings_status(code, own_ratings, listed):
    if code not in own_ratings:
        return "-"
    cards, generated, data_timestamp = own_ratings[code]
    status = f"{cards} cards, {'17Lands ' + to_date(data_timestamp) if generated else 'other'}"
    if code.lower() not in listed:
        status += ", NOT LISTED"
    return status


# ---------- download ----------

def download_sets(codes, sets_17lands):
    available = {info["code"]: info for info in sets_17lands}
    unknown = [code for code in codes if code not in available]
    if unknown:
        print(f"No 17Lands PremierDraft data for: {', '.join(unknown)}")
    todo = [(code, kind, file_status(code, kind, available[code])) for code in codes if code in available
            for kind in DATA_KINDS]
    todo = [item for item in todo if item[2] != "ok"]
    if not todo:
        print("Nothing to download, all files are here and up to date")
        return
    os.makedirs(DATA_DIR, exist_ok=True)
    total = sum(available[code][kind][0] for code, kind, _ in todo)
    print(f"Downloading {len(todo)} files of {len({code for code, _, _ in todo})} sets, {mb(total)} ...")
    for num, (code, kind, status) in enumerate(todo, 1):
        reason = " (update)" if status == "outdated" else ""
        download_file(DATA_URL.format(kind=kind, code=code), data_file_path(code, kind),
                      f"[{num}/{len(todo)}] {code} {kind} data{reason}")
    print(f"Downloaded {len(todo)} files")


# ---------- collect ----------

def collect_sets(codes, xmage_sets, own_ratings, listed):
    todo = []
    for code in codes:
        if not is_downloaded(code):
            print(f"{code}: no downloaded data, skip (use -download {code.lower()})")
        elif code in own_ratings and not own_ratings[code][1]:
            print(f"{code}: ratings file is not from 17Lands (other source), skip - remove it first to replace")
        else:
            todo.append(code)
    problems = check_environment()
    if todo and problems:
        raise SystemExit(f"{status_icon('error')} Can't generate ratings: {'; '.join(problems)}")

    failed = []
    for num, code in enumerate(todo, 1):
        prefix = f"[{num}/{len(todo)}] {code}"
        try:
            stats = calc_card_stats(code, prefix)
        except Exception as e:
            # one bad file must not stop other sets, its ratings file stays as is
            print(f"\n{prefix}: can't read data, skip: {type(e).__name__}: {e}")
            failed.append(code)
            continue
        data_timestamp = int(max(os.path.getmtime(data_file_path(code, kind)) for kind in DATA_KINDS))
        write_ratings(code, stats, listed, data_timestamp)
        xmage_cards = load_xmage_set_cards(xmage_sets[code][1]) if code in xmage_sets else set()
        unknown = [name for name in stats["name"] if name not in xmage_cards]
        print(f"{prefix}: {len(stats)} cards rated, top 5: {', '.join(stats['name'].head(5))}")
        if unknown:
            # bonus sheet cards from other sets, RateCard uses ratings by name, so keep it
            print(f"{prefix}: {len(unknown)} cards are not in XMage {code} set (other sets or unknown names): "
                  f"{', '.join(unknown[:10])}{' ...' if len(unknown) > 10 else ''}")
    if len(todo) > len(failed):
        listed[:] = update_sets_list()
    print(f"Collected {len(todo) - len(failed)} sets" + (f", failed {len(failed)}: {', '.join(failed)}" if failed else ""))


def calc_card_stats(code, prefix):
    import numpy as np
    import pandas as pd

    # draft data: take rate in the first picks of a pack
    path = data_file_path(code, "draft")
    pack_cols = [c for c in pd.read_csv(path, nrows=0).columns if c.startswith("pack_card_")]
    names = [c[len("pack_card_"):] for c in pack_cols]
    seen_early = np.zeros(len(names))
    taken_early = {}
    rows = 0
    bad_rows = 0
    # warning, some files have empty cells (example: AFR), so read numbers as float (empty -> NaN, NaN > 0 is false)
    for chunk in pd.read_csv(path, usecols=["pick_number", "pick"] + pack_cols, chunksize=50000,
                             dtype={c: "float32" for c in pack_cols}):
        rows += len(chunk)
        packs = chunk[pack_cols].to_numpy()
        bad_rows += int(np.isnan(packs).any(axis=1).sum())
        early = pd.to_numeric(chunk["pick_number"], errors="coerce").to_numpy() < EARLY_PICKS
        seen_early += (packs[early] > 0).sum(0)
        for name, count in chunk[early]["pick"].value_counts().items():
            taken_early[name] = taken_early.get(name, 0) + count
        print(f"\r{prefix}: draft data, {rows} picks   ", end="", flush=True)
    print()
    if bad_rows:
        print(f"{prefix}: draft data has {bad_rows} picks with empty pack cells (used as no card)")
    draft = pd.DataFrame({"name": names, "seen_early": seen_early})
    draft["take_rate"] = draft["name"].map(taken_early).fillna(0) / draft["seen_early"].replace(0, np.nan)

    # game data: games in hand win rate
    path = data_file_path(code, "game")
    header = pd.read_csv(path, nrows=0).columns
    hand_cols = [c for c in header if c.startswith("opening_hand_")]
    drawn_cols = [c for c in header if c.startswith("drawn_")]
    game_names = [c[len("opening_hand_"):] for c in hand_cols]
    games = np.zeros(len(game_names))
    wins = np.zeros(len(game_names))
    rows = 0
    bad_rows = 0
    for chunk in pd.read_csv(path, usecols=["won"] + hand_cols + drawn_cols, chunksize=50000,
                             dtype={c: "float32" for c in hand_cols + drawn_cols}):
        rows += len(chunk)
        # won can be bool, text or empty
        won_text = chunk["won"].astype(str).str.strip().str.lower()
        known = won_text.isin(["true", "false", "1", "0", "1.0", "0.0"]).to_numpy()
        bad_rows += int((~known).sum())
        won = won_text.isin(["true", "1", "1.0"]).to_numpy().astype(int)
        in_hand = ((chunk[hand_cols].to_numpy() > 0) | (chunk[drawn_cols].to_numpy() > 0)) & known[:, None]
        games += in_hand.sum(0)
        wins += (in_hand * won[:, None]).sum(0)
        print(f"\r{prefix}: game data, {rows} games   ", end="", flush=True)
    print()
    if bad_rows:
        print(f"{prefix}: game data has {bad_rows} games without a result (skipped)")
    game = pd.DataFrame({"name": game_names, "gih_games": games,
                         "gih_wr": wins / np.where(games > 0, games, np.nan)})

    stats = draft.merge(game, on="name")
    stats = stats[(stats["gih_games"] >= MIN_GAMES_IN_HAND) & stats["take_rate"].notna()
                  & ~stats["name"].isin(BASIC_LANDS)].copy()

    def z(x):
        return (x - x.mean()) / x.std()

    rating = z(stats["gih_wr"]) + z(stats["take_rate"])
    stats["rating"] = (100 * (rating - rating.min())).round().astype(int) + 1
    return stats.sort_values("rating", ascending=False)


def write_ratings(code, stats, listed, data_timestamp):
    path = os.path.join(RATINGS_DIR, code.lower() + ".csv")
    skipped = [name for name in stats["name"] if ":" in name]
    if skipped:
        # RateCard splits lines by ":", such names can't be rated
        print(f"{code}: skip cards with ':' in the name: {', '.join(skipped)}")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(GENERATED_MARK + "\n")
        f.write(DATA_DATE_LINE.format(date=to_date(data_timestamp), timestamp=data_timestamp) + "\n")
        for name, value in zip(stats["name"], stats["rating"]):
            if ":" not in name:
                f.write(f"{name}:{value}\n")


def update_sets_list():
    """
    Regenerate setsWithRatings.csv: keep its comment lines, list all rating files of the folder again (sorted).
    RateCard loads only listed sets, so new files can't be lost (warning, an empty line breaks the list reading).
    Returns the listed codes.
    """
    with open(RATINGS_SET_LIST, encoding="utf-8") as f:
        old_lines = f.read().splitlines()
    comments = [line for line in old_lines if line.startswith("#")] or DEFAULT_SETS_LIST_HEADER
    codes = sorted(code.lower() for code in load_own_ratings())
    new_lines = comments + codes
    if new_lines != old_lines:
        with open(RATINGS_SET_LIST, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(new_lines) + "\n")
        added = [code for code in codes if code not in old_lines]
        removed = [line for line in old_lines if line and not line.startswith("#") and line not in codes]
        print(f"Updated {os.path.basename(RATINGS_SET_LIST)}: {sets_count(len(codes))}"
              + (f", added {', '.join(added)}" if added else "") + (f", removed {', '.join(removed)}" if removed else ""))
    return codes


# ---------- status ----------

STATUS_ICONS = {"ok": ("\U0001F7E2", "[OK]"), "todo": ("\U0001F7E1", "[TODO]"), "error": ("\U0001F534", "[ERROR]")}


def status_icon(level):
    """Colored circle, or a text mark for consoles without unicode (example: old Windows code pages)"""
    emoji, text = STATUS_ICONS[level]
    try:
        emoji.encode(sys.stdout.encoding or "ascii")
        return emoji
    except (UnicodeEncodeError, LookupError):
        return text


def check_environment():
    """Problems that make the ratings generation impossible"""
    problems = []
    if sys.version_info < (3, 8):
        problems.append(f"python 3.8+ is needed, current is {sys.version.split()[0]}")
    missing = []
    for module in ("numpy", "pandas"):
        try:
            __import__(module)
        except ImportError:
            missing.append(module)
    if missing:
        problems.append(f"missing python modules: {', '.join(missing)} (install: pip install pandas numpy)")
    for path in (SETS_JAVA_DIR, RATINGS_DIR, RATINGS_SET_LIST):
        if not os.path.exists(path):
            problems.append(f"can't find {os.path.normpath(path)} (run the script from XMage sources)")
    return problems


def print_status(problems, not_downloaded, outdated, to_collect, to_clean):
    """One status line with the next step, returns the recommended menu item"""
    if problems:
        print(f"{status_icon('error')} Can't generate ratings: {'; '.join(problems)}")
        # downloads still work without pandas
        return "4" if outdated else ("2" if not_downloaded else None)
    if outdated:
        print(f"{status_icon('todo')} 17Lands has newer data for {sets_count(len(outdated))} ({', '.join(outdated)}): "
              f"update data (item 4), then collect ratings (item 3)")
        return "4"
    if not_downloaded:
        print(f"{status_icon('todo')} No ratings yet for {sets_count(len(not_downloaded))}: "
              f"download data (item 2, or item 1 for one set), then collect ratings (item 3)")
        return "2"
    if to_collect:
        print(f"{status_icon('todo')} New ratings needed for {sets_count(len(to_collect))} ({', '.join(to_collect)}): "
              f"collect ratings (item 3), then check and commit Mage/src/main/resources/ratings")
        return "3"
    clean_info = f", downloaded data can be deleted (item 5, {mb(files_size(to_clean))})" if to_clean else ""
    print(f"{status_icon('ok')} All ratings are up to date with 17Lands{clean_info}")
    return "5" if to_clean else None


