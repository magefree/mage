#!/usr/bin/env python3
"""
Generate draft ratings for AI/bots (Mage/src/main/resources/ratings/<code>.csv) from 17Lands public datasets.

Data from 17Lands.com (https://www.17lands.com/public_datasets), license CC BY 4.0. Only PremierDraft files are used:
draft data (picks) and game data (games), both are needed for a set.

Usage (run from any folder, files are in Utils):
  gen-draft-rates-17Lands.py                  - show sets table (our ratings, 17Lands data, downloads) and a menu
  gen-draft-rates-17Lands.py -download        - download data of all sets without ratings + update outdated data
  gen-draft-rates-17Lands.py -download fra,hob - download data of the sets (missing or outdated files only)
  gen-draft-rates-17Lands.py -collect         - generate ratings for downloaded sets without ratings or with outdated ratings
  gen-draft-rates-17Lands.py -collect fra,hob  - generate ratings for the sets (overwrite own 17Lands files)
  gen-draft-rates-17Lands.py -clean           - delete downloaded data of the sets with generated ratings (and broken downloads)

17Lands data is cached in Utils/data/17lands/ (sets list refetched if older than 24h, data files are big: ~100 MB per set).
A downloaded file keeps the 17Lands file date, so the script knows outdated files (17Lands updates new sets for weeks)
and outdated ratings (generated file keeps the date of its data). Data files are never deleted automatically, use -clean.
Every run regenerates Mage/src/main/resources/ratings/setsWithRatings.csv: keeps its comment lines and lists all rating
files of the folder again (RateCard loads only listed sets).
Needs pandas and numpy for the ratings generation (pip install pandas).

Rating of a card = z(games in hand win rate) + z(take rate in the first 4 picks of a pack), only cards with 500+ games
in hand, basic lands skipped. Nonbasic lands stay in the file: a card without a file rating gets the rarity score of
RateCard, which is too high against the normalized file ratings (bots take too many nonbasic lands then).
RateCard normalizes every file to 0..100, so only the cards order matters.

@author: JayDi85
"""
